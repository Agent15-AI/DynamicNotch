import AppKit
import Carbon.HIToolbox

/// Clipboard history, without polling.
///
/// This was on the "deliberately not built" list, and the reason still holds:
/// macOS posts nothing when the pasteboard changes, so every clipboard manager
/// reads `changeCount` on a timer, several times a second, forever. That one
/// timer would cost more wakeups than the rest of this app together.
///
/// What changed is the observation that a copy almost always leaves the app it
/// was made in. You copy in one place and paste in another, and switching apps
/// is an event macOS does announce. So the pasteboard is read at the moments a
/// new copy would matter - an app coming forward, the island opening, the
/// command bar opening - and at no other time. A copy in one app followed by a
/// second copy in the same app, with no switch between, keeps only the second.
/// That is the whole cost of having no timer, and it is written down here
/// rather than discovered.
///
/// Text, images, files and colours, 60 entries plus whatever is pinned, stored
/// under Application Support readable only by you. Anything a password manager marks as concealed or transient is never
/// read - the `org.nspasteboard` convention 1Password, Bitwarden and the rest
/// follow - and nor is anything copied from those apps.
@MainActor
@Observable
final class Clipboard {
    static let shared = Clipboard()

    enum Kind: String, Codable {
        case text, image, file, colour
    }

    struct Clip: Identifiable, Codable, Equatable {
        var id = UUID()
        var text: String
        var date: Date
        /// Bundle id of the app that was in front when it was copied.
        var app: String?
        var kind: Kind = .text
        /// Pinned clips are never evicted and never cleared.
        var pinned = false
        /// File name under `clipboard/`, for an image. The bytes are not held
        /// in memory or in the JSON - a screenshot would be megabytes of
        /// base64 in a file re-read on every launch.
        var image: String?
        /// Paths, for a file copy. Held as paths rather than bookmarks: these
        /// are re-offered to the pasteboard, not opened, and a stale path is
        /// pruned when the row is used.
        var files: [String] = []

        var isText: Bool { kind == .text || kind == .colour }
    }

    private(set) var clips: [Clip] = []

    /// Pinned first, then newest. A pin is only useful if it stays in sight.
    var ordered: [Clip] { clips.filter(\.pinned) + clips.filter { !$0.pinned } }

    /// Internal so `RenderCheck` can pick up what is already on the clipboard.
    var lastChange = NSPasteboard.general.changeCount
    /// The app in front before the current one - where a copy found on switch
    /// was most likely made.
    private var previousApp: String?
    private var save: DispatchWorkItem?
    private var started = false
    private var autoClear: DispatchWorkItem?
    private var watchingLock = false

    private static let limit = 60
    private static let maxLength = 20_000
    /// 24 MB. Comfortably a Retina screenshot, nowhere near a RAW photo.
    private static let maxImageBytes = 24 * 1024 * 1024
    /// nspasteboard.org markers, plus the older private ones some apps still use.
    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "net.antelle.keeweb",
    ]
    private static let passwordManagers: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.dashlane.dashlanephonefinal", "in.sinew.Enpass-Desktop",
    ]

    nonisolated private static var file: URL {
        let folder = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)
            .first?.appendingPathComponent("DynamicIsland", isDirectory: true)
            ?? URL(fileURLWithPath: NSHomeDirectory())
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        return folder.appendingPathComponent("clipboard.json")
    }

    /// PNGs for image clips, beside the JSON that names them.
    nonisolated static var imageFolder: URL {
        file.deletingLastPathComponent().appendingPathComponent("clipboard", isDirectory: true)
    }

    private init() {}

    func start() {
        guard !started else { return }
        started = true
        if let data = try? Data(contentsOf: Self.file),
           let stored = try? JSONDecoder().decode([Clip].self, from: data) {
            clips = stored
        }
        previousApp = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { note in
            let app = (note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication)?.bundleIdentifier
            MainActor.assumeIsolated { Clipboard.shared.appActivated(app) }
        }
    }

    private func appActivated(_ bundleID: String?) {
        capture(source: previousApp)
        previousApp = bundleID
    }

    /// Reads the pasteboard if it changed since last time. Called only at the
    /// moments listed above - never on a timer.
    func capture(source: String? = NSWorkspace.shared.frontmostApplication?.bundleIdentifier) {
        guard Settings.shared.clipboard else { return }
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = Set(pasteboard.types?.map(\.rawValue) ?? [])
        guard types.isDisjoint(with: Self.secretTypes),
              !(source.map(Self.passwordManagers.contains) ?? false)
        else { return }

        // Files first, then an image, then text. The order matters: copying a
        // file in the Finder also puts its name on the pasteboard as a string,
        // and copying an image from a browser puts its URL there too, so
        // checking text first would record the label instead of the thing.
        guard var clip = fileClip(pasteboard, source)
                ?? imageClip(pasteboard, source)
                ?? textClip(pasteboard, source)
        else { return }

        // A re-copy of something already held moves it up rather than making a
        // second row, and keeps the pin.
        //
        // The label alone is not the thing. "Image 2940×1912" is every full-
        // screen screenshot and "3 files" is any three files, so matching on it
        // replaced one copy with a different one and deleted the first image.
        if let existing = clips.first(where: {
            $0.kind == clip.kind && $0.text == clip.text && $0.files == clip.files && sameImage($0, clip)
        }) {
            clip.pinned = existing.pinned
            clip.id = existing.id
            discard(existing, keepingImageFor: clip)
            clips.removeAll { $0.id == existing.id }
        }
        clips.insert(clip, at: 0)
        evict()
        persist()
        armAutoClear()

        // Copying the whole message and then deleting the words by hand is the
        // actual chore here, so the offer is only worth making when the code is
        // buried in something longer.
        guard clip.isText, Settings.shared.verificationCodes,
              let code = Self.code(in: clip.text), code != clip.text
        else { return }
        HUD.shared.show(.verification(code: code), for: 4.5)
    }

    // MARK: - Reading each kind

    private func fileClip(_ pasteboard: NSPasteboard, _ source: String?) -> Clip? {
        let urls = pasteboard.readObjects(
            forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
        guard let urls, !urls.isEmpty else { return nil }
        let paths = urls.map(\.path)
        let name = urls.count == 1
            ? urls[0].lastPathComponent
            : "\(urls.count) files"
        return Clip(text: name, date: .now, app: source, kind: .file, files: paths)
    }

    private func imageClip(_ pasteboard: NSPasteboard, _ source: String?) -> Clip? {
        guard let image = NSImage(pasteboard: pasteboard),
              let tiff = image.tiffRepresentation,
              let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
        else { return nil }
        // A copied image is usually a screenshot; a 100 MB one is usually a
        // mistake, and keeping it would mean re-writing it on every change.
        guard png.count <= Self.maxImageBytes else { return nil }
        let name = "\(UUID().uuidString).png"
        try? FileManager.default.createDirectory(at: Self.imageFolder, withIntermediateDirectories: true)
        guard (try? png.write(to: Self.imageFolder.appendingPathComponent(name), options: .atomic)) != nil
        else { return nil }
        let size = image.size
        return Clip(text: "Image \(Int(size.width))×\(Int(size.height))", date: .now,
                    app: source, kind: .image, image: name)
    }

    private func textClip(_ pasteboard: NSPasteboard, _ source: String?) -> Clip? {
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.count <= Self.maxLength
        else { return nil }
        return Clip(text: text, date: .now, app: source,
                    kind: Self.hex(in: text) == nil ? .text : .colour)
    }

    /// `#1D9BF0` or `1d9bf0`, and nothing else on the clipboard. Narrow on
    /// purpose: six hex characters are also a git short hash and half the
    /// identifiers in a codebase, so a bare run only counts when it is the
    /// entire clipboard and carries the hash.
    static func hex(in text: String) -> String? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard trimmed.hasPrefix("#") else { return nil }
        let digits = String(trimmed.dropFirst())
        guard digits.count == 6 || digits.count == 8,
              digits.allSatisfy(\.isHexDigit)
        else { return nil }
        return "#" + digits.uppercased()
    }

    /// The swatch colour for a `.colour` clip.
    static func colour(for clip: Clip) -> NSColor? {
        guard let hex = hex(in: clip.text) else { return nil }
        let digits = Array(hex.dropFirst())
        func channel(_ index: Int) -> CGFloat {
            CGFloat(UInt8(String(digits[index * 2...index * 2 + 1]), radix: 16) ?? 0) / 255
        }
        return NSColor(srgbRed: channel(0), green: channel(1), blue: channel(2),
                       alpha: digits.count == 8 ? channel(3) : 1)
    }

    /// Byte-for-byte, and only ever asked about two images whose sizes already
    /// match - so at most one PNG is read per copy.
    private func sameImage(_ a: Clip, _ b: Clip) -> Bool {
        guard let left = a.image, let right = b.image else { return a.image == b.image }
        let folder = Self.imageFolder
        return (try? Data(contentsOf: folder.appendingPathComponent(left)))
            == (try? Data(contentsOf: folder.appendingPathComponent(right)))
    }

    func image(for clip: Clip) -> NSImage? {
        guard let name = clip.image else { return nil }
        return NSImage(contentsOf: Self.imageFolder.appendingPathComponent(name))
    }

    // MARK: - Pinning and eviction

    func togglePin(_ clip: Clip) {
        guard let index = clips.firstIndex(where: { $0.id == clip.id }) else { return }
        clips[index].pinned.toggle()
        persist()
    }

    /// Pinned clips are exempt. Everything else falls off the end.
    private func evict() {
        var unpinned = clips.filter { !$0.pinned }.count
        guard unpinned > Self.limit else { return }
        for clip in clips.reversed() where unpinned > Self.limit {
            guard !clip.pinned else { continue }
            discard(clip)
            clips.removeAll { $0.id == clip.id }
            unpinned -= 1
        }
    }

    /// Removes the backing PNG, unless the replacement clip still points at it.
    private func discard(_ clip: Clip, keepingImageFor replacement: Clip? = nil) {
        guard let name = clip.image, replacement?.image != name else { return }
        try? FileManager.default.removeItem(at: Self.imageFolder.appendingPathComponent(name))
    }

    // MARK: - Auto-clear

    /// Wipes the system pasteboard after a delay, or on lock and sleep.
    ///
    /// The history is untouched - this is about what the *next* app can paste,
    /// which is the whole risk of a clipboard holding a password you pasted an
    /// hour ago.
    ///
    /// One work item, re-armed on each copy. Not a timer: nothing is scheduled
    /// while the clipboard has not changed, and the item is cancelled the
    /// moment a new copy replaces it.
    private func armAutoClear() {
        autoClear?.cancel()
        autoClear = nil
        let minutes = Settings.shared.clipboardClearMinutes
        guard minutes > 0 else { return }
        let work = DispatchWorkItem { MainActor.assumeIsolated { Clipboard.shared.wipe(reason: "Timed out") } }
        autoClear = work
        DispatchQueue.main.asyncAfter(deadline: .now() + minutes * 60, execute: work)
    }

    func watchLock() {
        guard !watchingLock else { return }
        watchingLock = true
        for name in ["com.apple.screenIsLocked", "com.apple.screensaver.didstart"] {
            DistributedNotificationCenter.default().addObserver(
                forName: Notification.Name(name), object: nil, queue: .main
            ) { _ in
                MainActor.assumeIsolated {
                    guard Settings.shared.clipboardClearOnLock else { return }
                    Clipboard.shared.wipe(reason: "Screen locked")
                }
            }
        }
        NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.willSleepNotification, object: nil, queue: .main
        ) { _ in
            MainActor.assumeIsolated {
                guard Settings.shared.clipboardClearOnLock else { return }
                Clipboard.shared.wipe(reason: "Mac slept")
            }
        }
    }

    private func wipe(reason: String) {
        let pasteboard = NSPasteboard.general
        guard pasteboard.string(forType: .string) != nil || pasteboard.types?.isEmpty == false else { return }
        pasteboard.clearContents()
        lastChange = pasteboard.changeCount
        autoClear?.cancel()
        autoClear = nil
        HUD.shared.show(
            .utility(symbol: "clipboard", title: "Clipboard cleared", detail: reason), for: 1.6)
    }

    /// A one-time code inside copied text.
    ///
    /// Deliberately narrow. Any 4-8 digit run matches far too much - a year, a
    /// price, a flight number - so a code is only claimed when the text says it is
    /// one, or when the whole clipboard is nothing but the digits. Spaces and
    /// hyphens inside the run are dropped, because "123 456" is one code.
    static func code(in text: String) -> String? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        // A message, not a document. Anything longer is prose that happens to
        // contain the word "code".
        guard trimmed.count <= 300 else { return nil }

        let bare = trimmed.filter { !$0.isWhitespace && $0 != "-" }
        if bare.count >= 4, bare.count <= 8, bare.allSatisfy(\.isNumber) { return bare }

        let lower = trimmed.lowercased()
        let keywords = ["code", "otp", "passcode", "one-time", "one time", "verification",
                        "verify", "2fa", "authentication", "pin", "sign in", "sign-in"]
        guard keywords.contains(where: lower.contains) else { return nil }

        // Every run of digits, joined across a single space or hyphen. The first
        // run of the right length wins rather than the longest: "expires in 10
        // minutes" sits after the code often enough, and a ten-digit phone number
        // in the same message must not disqualify the code beside it.
        var runs: [String] = []
        var current = ""
        var afterSeparator = false
        for character in trimmed {
            if character.isNumber {
                current.append(character)
                afterSeparator = false
            } else if character == " " || character == "-", !current.isEmpty, !afterSeparator {
                // Holds the run open once, so "123 456" is one code.
                afterSeparator = true
            } else {
                if !current.isEmpty { runs.append(current) }
                current = ""
                afterSeparator = false
            }
        }
        if !current.isEmpty { runs.append(current) }
        return runs.first { $0.count >= 4 && $0.count <= 8 }
    }

    /// Presses ⌘V in whatever app is in front.
    ///
    /// Shared by the history rows and by plain-text paste, which are the same
    /// gesture with a different clipboard behind it.
    static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    /// Puts a clip back on the clipboard, and moves it to the top.
    ///
    /// Written back as what it was: a file copy goes back as file URLs so the
    /// Finder can paste it, an image as image data. Putting everything back as
    /// a string is what makes most clipboard managers text-only in practice
    /// even when they show you a thumbnail.
    func copy(_ clip: Clip) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch clip.kind {
        case .file:
            let urls = clip.files
                .filter { FileManager.default.fileExists(atPath: $0) }
                .map { URL(fileURLWithPath: $0) as NSURL }
            if urls.isEmpty {
                // Every path is gone - the files were moved or deleted since.
                HUD.shared.show(.utility(symbol: "questionmark.folder", title: "Files are gone",
                                         detail: clip.text), for: 2.0)
                remove(clip)
                return
            }
            pasteboard.writeObjects(urls)
        case .image:
            if let image = image(for: clip) {
                pasteboard.writeObjects([image])
            } else {
                remove(clip)
                return
            }
        case .text, .colour:
            pasteboard.setString(clip.text, forType: .string)
        }
        lastChange = pasteboard.changeCount

        var moved = clip
        moved.date = .now
        clips.removeAll { $0.id == clip.id }
        clips.insert(moved, at: 0)
        persist()
        armAutoClear()
    }

    /// Copies, then presses ⌘V in whatever app is in front. The island never
    /// takes focus, so the front app is the one you were typing in. Needs the
    /// Accessibility permission the menu bar module already holds; without it
    /// this is a copy, and the receipt says so.
    func paste(_ clip: Clip) {
        copy(clip)
        PanelManager.shared.collapseAll()
        guard AXIsProcessTrusted() else {
            HUD.shared.show(.utility(symbol: "doc.on.clipboard.fill", title: "Copied", detail: "Press ⌘V to paste"), for: 1.6)
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            Self.pressCommandV()
        }
    }

    func remove(_ clip: Clip) {
        discard(clip)
        clips.removeAll { $0.id == clip.id }
        persist()
    }

    /// Keeps what was pinned. A pin is the user saying "not this one".
    func clear() {
        for clip in clips where !clip.pinned { discard(clip) }
        clips.removeAll { !$0.pinned }
        persist()
    }

    private func persist() {
        save?.cancel()
        let work = Self.writer(clips)
        save = work
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 0.6, execute: work)
    }

    /// The pending debounced write, now. Run on quit.
    func flush() {
        save?.perform()
    }

    /// Nonisolated for the reason `Notes.writer` gives: a work item closure
    /// made on the main actor traps when a background queue runs it.
    nonisolated private static func writer(_ snapshot: [Clip]) -> DispatchWorkItem {
        DispatchWorkItem {
            guard let data = try? JSONEncoder().encode(snapshot) else { return }
            try? data.write(to: file, options: .atomic)
            // Clipboard text can be anything; keep it to this user.
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
        }
    }
}
